import random as r

# 1. リスト「l(L 小文字)」に好きな整数を3個入れて，
# その中からランダムに1つ数字を選んだr1,r2を作ってください.
# r1とr2が等しかったら，「r1とr2は等しいです」と出力し，
# 等しくなかったら，「r1とr2は違います」と出力してください.

# 2. リストlの中からランダムに1つ数字を選び，変数aとしてください．
# その数字が3で割りきれる場合は「3で割れます」と出力し，
# 5で割りきれる場合は「5で割れます」と出力してください.
# ただし，両方に当てはまる場合は「15 で割れます」と出力してください.

l=[3,15,18]
r1 = r.choice(l)
r2 = r.choice(l)

if r1 == r2:
    print("r1とr2は等しいです")
else:
    print("r1とr2は違います")

a = r.choice(l)
if a % 3 == 0 and a % 5 == 0:
    print("15 で割れます")
elif a % 3 == 0:
    print("3で割れます")
elif a % 5 == 0:
    print("5で割れます")
